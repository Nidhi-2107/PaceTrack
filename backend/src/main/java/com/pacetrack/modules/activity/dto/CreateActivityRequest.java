package com.pacetrack.modules.activity.dto;

import jakarta.validation.Valid;
import jakarta.validation.constraints.*;

import java.time.Instant;
import java.util.List;

public record CreateActivityRequest(

    @NotBlank(message = "Activity type is required")
    String activityType,

    @NotBlank(message = "Title is required")
    @Size(min = 1, max = 120, message = "Title must be between 1 and 120 characters")
    String title,

    @NotNull(message = "Start time is required")
    Instant startTime,

    @NotNull(message = "End time is required")
    Instant endTime,

    @NotNull(message = "Distance is required")
    @DecimalMin(value = "0.0", message = "Distance cannot be negative")
    Double distanceMeters,

    @Min(value = 0, message = "Step count cannot be negative")
    Integer stepCount,

    String privacyLevel,

    // idempotencyKey generated by client to prevent duplicate submissions on retry
    @Size(max = 128, message = "Idempotency key must be at most 128 characters")
    String idempotencyKey,

    @Valid
    List<WaypointRequest> waypoints
) {}

